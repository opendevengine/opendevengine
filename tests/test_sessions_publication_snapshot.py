    def test_outcome_counts_only_blocking_rejections_for_automatic_policy(self):
        from contextlib import contextmanager
        from opendevengine.sessions.attempt import Attempt
        sid = self.completed(generated=True)
        with self.store.transaction() as db:
            db.execute("INSERT INTO validation_runs(id,session_id,ordinal,command_json,source,status,required,environment_json) "
                       "VALUES('passed',?,1,'{}','proposed','passed',1,'{}')", (sid,))
        @contextmanager
        def transaction():
            with self.store.transaction() as db:
                yield db, {'state': 'validating', 'stop_reason': None, 'stop_requested': False,
                           'outcome_json': '{}'}
        attempt = Attempt.__new__(Attempt)
        attempt.svc = mock.Mock(store=self.store, clock=self.sessions.clock)
        attempt.svc.source_policy.return_value = {'available': True}
        attempt.sid, attempt.lost, attempt.unverified_edits = sid, False, False
        attempt.tool_calls, attempt.observed_model = 0, None
        attempt.session = {'publication_json': canonical({'policy': 'on_success_draft'})}
        attempt.last_checkpoint = {'id': 'cp', 'stats': {'files': 2, 'rejected': 1}}
        attempt.record_revocation = mock.Mock()
        attempt.contain = mock.Mock(return_value={'confirmed': True})
        attempt.tx = transaction
        for status, count, eligible in [('added', 0, True), ('modified', 1, False), ('deleted', 1, False)]:
            with self.subTest(status=status):
                self.mutate_artifact(sid, 'checkpoint', lambda cp: cp['rejected'][0].update(status=status))
                attempt._finish('completed', None, None)
                outcome = json.loads(attempt.svc.transition.call_args.kwargs['outcome_json'])
                self.assertEqual(outcome['rejected_paths'], count)
                self.assertEqual(outcome['publication_eligible'], eligible)

